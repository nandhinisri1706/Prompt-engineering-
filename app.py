import streamlit as st

from llm import generate_response
from prompt_template import build_prompt

st.set_page_config(
    page_title="PromptCraft AI",
    page_icon="🧠",
    layout="centered"
)


st.title("🧠 PromptCraft AI")

st.write(
    "An interactive Prompt Engineering Lab "
    "for exploring different prompting techniques "
    "using the Qwen Large Language Model."
)

st.divider()

st.subheader("Select Prompting Technique")

technique = st.selectbox(
    "Choose a technique",
    [
        "Zero-Shot",
        "One-Shot",
        "Few-Shot",
        "CoT",
        "Manual CoT",
        "ToT",
        "MCOT"
    ]
)


st.subheader("Enter Your Task")

task = st.text_area(
    "Question / Task",

    placeholder=(
        "Example: Explain the difference between "
        "Artificial Intelligence and Machine Learning."
    ),

    height=130
)


st.subheader("Model Parameters")

temperature = st.slider(
    "Temperature",

    min_value=0.0,

    max_value=1.0,

    value=0.2,

    step=0.1,

    help=(
        "Lower values produce more focused and "
        "predictable responses. Higher values "
        "produce more creative responses."
    )
)


max_tokens = st.slider(
    "Maximum Tokens",

    min_value=100,

    max_value=2000,

    value=500,

    step=100,

    help=(
        "Controls the maximum number of tokens "
        "generated by the model."
    )
)

st.divider()


if st.button(
    "Generate Response",
    type="primary",
    use_container_width=True
):

    if task.strip() == "":

        st.warning(
            "Please enter a question or task."
        )

    else:

        try:


            final_prompt = build_prompt(
                technique,
                task
            )


            st.subheader("Generated Prompt")

            st.code(
                final_prompt,
                language="text"
            )



            with st.spinner(
                "Qwen is generating the response..."
            ):

                answer = generate_response(
                    final_prompt,
                    temperature,
                    max_tokens
                )

            st.subheader("LLM Response")

            st.write(answer)


        except Exception as e:

            st.error(
                f"Error while generating response: {e}"
            )

st.divider()

st.caption(
    "PromptCraft AI | Prompt Engineering Lab"
)